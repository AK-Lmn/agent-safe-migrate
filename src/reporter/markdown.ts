import type { MigrationReport } from '../core/types.js';
import { basename } from 'node:path';

/**
 * Markdown reporter — generates a report suitable for PR comments
 * or GitHub Action annotations.
 */
export function renderMarkdownReport(report: MigrationReport): string {
  const lines: string[] = [];
  const { migration, execution, violations, passed, hasDestructive } = report;

  // Header
  lines.push('## 🛡️ Migration Guardian Report');
  lines.push('');

  // Status badge
  if (passed) {
    lines.push('**Status: ✅ PASSED**');
  } else {
    lines.push('**Status: ❌ FAILED**');
  }
  lines.push('');

  // Migration info
  const formatLabel =
    migration.format === 'raw-sql'
      ? 'Raw SQL'
      : migration.format === 'prisma'
        ? 'Prisma'
        : 'Drizzle';

  lines.push(`**Format:** ${formatLabel}`);
  lines.push(`**Files:** ${migration.files.map((f) => '`' + basename(f.path) + '`').join(', ')}`);
  lines.push('');

  // Execution
  if (execution) {
    lines.push('### ⚡ Execution');
    lines.push('');

    if (execution.success) {
      lines.push(
        `✅ Executed successfully (${execution.statementsExecuted} statements, ${execution.executionTimeMs}ms)`
      );
    } else {
      lines.push('❌ Execution failed');
      lines.push('');
      lines.push('```');
      lines.push(execution.error || 'Unknown error');
      lines.push('```');
    }

    lines.push('');
  }

  // Violations
  if (violations.length > 0) {
    lines.push('### 🔍 Rule Violations');
    lines.push('');
    lines.push('| Rule | Issue | Severity |');
    lines.push('|------|-------|----------|');

    for (const v of violations) {
      const sevIcon = v.severity === 'error' ? '❌ error' : '⚠️ warning';
      lines.push(`| ${v.ruleId} | ${v.ruleName} | ${sevIcon} |`);
    }

    lines.push('');

    // Details
    for (const v of violations) {
      const icon = v.severity === 'error' ? '❌' : '⚠️';
      lines.push(`#### ${icon} ${v.ruleId}: ${v.ruleName}`);
      lines.push('');
      lines.push(v.message);

      if (v.suggestion) {
        lines.push('');
        lines.push('**Suggested fix:**');
        lines.push('');
        lines.push('```sql');
        lines.push(v.suggestion);
        lines.push('```');
      }

      lines.push('');
    }
  } else {
    lines.push('### 🔍 Rule Analysis');
    lines.push('');
    lines.push('✅ No violations found');
    lines.push('');
  }

  // Destructive warning
  if (hasDestructive) {
    lines.push('> ⚠️ **DESTRUCTIVE OPERATIONS DETECTED** — Use `--confirm-destructive` to proceed');
    lines.push('');
  }

  // Footer
  lines.push('---');
  lines.push(`*Generated by [mgcheck](https://github.com/yourusername/mgcheck) at ${report.timestamp}*`);

  return lines.join('\n');
}
